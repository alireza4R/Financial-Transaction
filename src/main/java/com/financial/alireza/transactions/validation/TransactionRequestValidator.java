package com.financial.alireza.transactions.validation;

import com.financial.alireza.transactions.dto.CreateTransactionRequest;
import jakarta.validation.ConstraintValidator;
import jakarta.validation.ConstraintValidatorContext;

public class TransactionRequestValidator implements ConstraintValidator<ValidTransactionRequest, CreateTransactionRequest> {

    @Override
    public boolean isValid(CreateTransactionRequest request, ConstraintValidatorContext context) {

        if (request == null || request.transactionType() == null) {
            return true;
        }

        return switch (request.transactionType()) {
            case DEPOSIT -> {
                if (request.destination() == null) {
                    yield reject(
                            context,
                            "destination",
                            "Destination is required for deposit"
                    );
                }

                yield true;
            }

            case WITHDRAW -> {
                if (request.source() == null) {
                    yield reject(
                            context,
                            "source",
                            "Source is required for withdrawal"
                    );
                }

                yield true;
            }

            case TRANSFER -> {
                if (request.source() == null) {
                    yield reject(
                            context,
                            "source",
                            "Source is required for transfer"
                    );
                }

                if (request.destination() == null) {
                    yield reject(
                            context,
                            "destination",
                            "Destination is required for transfer"
                    );
                }

                if (request.source().equals(request.destination())) {
                    yield reject(
                            context,
                            "destination",
                            "Source and destination must differ"
                    );
                }

                yield true;
            }

            case FEE -> reject(
                    context,
                    "transactionType",
                    "Fee transactions are generated by the system"
            );
        };
    }

    private boolean reject(
            ConstraintValidatorContext context,
            String field,
            String message) {

        context.disableDefaultConstraintViolation();

        context.buildConstraintViolationWithTemplate(message)
                .addPropertyNode(field)
                .addConstraintViolation();

        return false;
    }
}